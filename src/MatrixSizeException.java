// class описує тип об’єктів; new створює конкретний об’єкт і викликає його конструктор. public робить клас
// доступним ззовні; final у заголовку класу, якщо він є, забороняє створювати підкласи, але сам по собі не робить
// поля незмінними.
// extends задає єдиний батьківський клас. Виклик методу через змінну базового типу все одно обирає реалізацію
// фактичного об’єкта — так працює поліморфізм, знайомий і з Python.
public final class MatrixSizeException extends ArithmeticException { // Власний тип помилки арифметичних обмежень згідно з методичкою.
    // super(...) викликає конструктор батьківського класу для цього самого об’єкта, приблизно як
    // super().__init__(...) у Python. У цих проєктах із рівнем Java 17 цей виклик стоїть першим у конструкторі:
    // спочатку готуємо батьківську частину, потім власні поля.
    public MatrixSizeException(String message) { super(message); } // Передаємо пояснення базовому класу винятку.
}
