import javax.swing.JPanel; // Панель є областю власного малювання.
import javax.swing.Timer; // Swing Timer викликає обробник у потоці EDT.
import java.awt.Color; // Колір напрямного та обертового відрізків.
import java.awt.Graphics; // Початковий графічний контекст Swing.
import java.awt.Graphics2D; // Розширений контекст підтримує якісне малювання.
import java.awt.BasicStroke; // Керуємо товщиною ліній.
import java.awt.RenderingHints; // Увімкнення згладжування контурів.
// class описує тип об’єктів; new створює конкретний об’єкт і викликає його конструктор. public робить клас
// доступним ззовні; final у заголовку класу, якщо він є, забороняє створювати підкласи, але сам по собі не робить
// поля незмінними.
// extends задає єдиний батьківський клас. Виклик методу через змінну базового типу все одно обирає реалізацію
// фактичного об’єкта — так працює поліморфізм, знайомий і з Python.
public final class RotationPanel extends JPanel { // Точка опори рухається по горизонтальному напрямному відрізку, синій відрізок обертається навколо неї.
    private double time = 0; // Накопичений час анімації у секундах.
    // nanoTime — годинник для вимірювання проміжків, як time.perf_counter_ns() у Python. Його значення не є
    // календарною датою; зміст має різниця двох показів, яку не збиває переведення системного годинника.
    private long previous = System.nanoTime(); // Монотонний годинник для вимірювання інтервалів.
    // private забороняє прямий доступ до поля з інших класів. final дозволяє присвоїти поле лише один раз; для
    // посилання це заборона замінити об’єкт, а не заборона змінювати його вміст, якщо сам об’єкт змінний.
    private final Timer timer; // Таймер зберігається для коректної зупинки при закритті.
    public RotationPanel() { // Ініціалізуємо панель і механізм оновлення.
        setBackground(Color.WHITE); // Біле тло робить лінії та написи читабельними.
        // Це javax.swing.Timer: затримка задана в мілісекундах, 16 мс дає орієнтир близько 60 подій за секунду.
        // Обробник працює на EDT, а не в окремому потоці Timer; точний інтервал не гарантований, тому рух рахуємо
        // за фактичним часом.
        timer = new Timer(16, event -> { // Приблизно 60 оновлень на секунду без окремого робочого потоку.
            long now = System.nanoTime(); // Зчитуємо поточний монотонний час.
            // У наносекунді 1/1_000_000_000 секунди, тому ділимо різницю на мільярд. .0 робить ділення дробовим, а
            // підкреслення лише полегшують читання числа й не впливають на значення.
            time += (now - previous) / 1_000_000_000.0; // Переводимо наносекунди в секунди незалежно від частоти кадрів.
            previous = now; // Зберігаємо початок наступного інтервалу.
            // repaint() просить Swing намалювати новий кадр пізніше через чергу подій. Він не викликає
            // paintComponent негайно; кілька запитів Swing може об’єднати, щоб не малювати зайві кадри.
            repaint(); // Просимо Swing перемалювати панель, не викликаючи paintComponent напряму.
        });
        timer.start(); // Запускаємо події таймера.
    }
    public void stop() { timer.stop(); } // Зупиняємо таймер, коли вікно закривається.
    // @Override просить компілятор перевірити, що метод справді замінює успадкований метод або реалізує метод
    // інтерфейсу. Якщо помилитися в назві чи параметрах, Java повідомить про це ще до запуску.
    @Override protected void paintComponent(Graphics graphics) { // Swing викликає метод на EDT, коли панель треба оновити.
        // Спочатку викликаємо малювання батьківського JPanel, зокрема очищення тла. Без цього попередні положення
        // фігур могли б залишати сліди на наступних кадрах.
        super.paintComponent(graphics); // Очищуємо попередній кадр і малюємо тло.
        // create() робить копію графічного контексту; (Graphics2D) уточнює його фактичний тип для методів
        // масштабування й налаштувань. Зміна кольору чи масштабу цієї копії не вплине на малювання інших
        // компонентів.
        Graphics2D g = (Graphics2D) graphics.create(); // Створюємо копію контексту, щоб локальні налаштування не витікали назовні.
        g.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON); // Згладжуємо похилі лінії.
        int left = 150; // Ліва межа напрямного відрізка.
        int right = Math.max(left, getWidth() - 150); // Права межа враховує поточну ширину панелі.
        // Обидва операнди цілі, тому Java ділить націло і відкидає дробову половину пікселя. Тут це доречно для
        // координати; у Python звичайне / дало б float, а схоже ціле ділення записали б //.
        int cy = getHeight() / 2; // Напрямний відрізок проходить посередині панелі.
        // sin і cos приймають кут у радіанах, як math.sin/cos у Python. Вони дають проєкції руху на осі; екранна
        // вісь y спрямована вниз, тому видимий напрям обертання треба оцінювати саме в екранних координатах.
        // sin лежить між -1 та 1; додавання 1 і ділення на 2 переводять його в [0,1]. Множник 0.7 задає темп руху
        // точки опори, незалежний від кута обертання синього відрізка.
        double fraction = (1 + Math.sin(time * 0.7)) / 2; // Значення 0..1 задає плавний рух точки туди й назад.
        // При fraction=0 отримуємо left, при fraction=1 — right, а проміжні значення лежать між ними. Це
        // перетворює безрозмірну частку шляху на горизонтальну координату.
        double cx = left + (right - left) * fraction; // Перетворюємо частку шляху на екранну координату x точки опори.
        double angle = time; // Кутова швидкість становить 1 радіан за секунду.
        double dx = 110 * Math.cos(angle); // Горизонтальна складова половини обертового відрізка.
        double dy = 110 * Math.sin(angle); // Вертикальна складова половини відрізка.
        g.setColor(Color.LIGHT_GRAY); // Напрямний шлях малюємо нейтральним кольором.
        g.drawLine(left, cy, right, cy); // Показуємо відрізок, по якому переміщується точка.
        g.setStroke(new BasicStroke(4)); // Обертову лінію робимо помітнішою.
        g.setColor(new Color(30, 95, 180)); // Вибираємо синій колір обертового відрізка.
        // (int) — явне перетворення на 32-бітне ціле: дробова частина відкидається до нуля, наприклад 3.9 → 3 і
        // -3.9 → -3. Це не округлення до найближчого. Як int(x) для звичайних скінченних Python float, але Java
        // int має межі, тоді як Python int може зростати.
        // Пари (cx-dx, cy-dy) та (cx+dx, cy+dy) симетричні відносно точки опори. Довжина кожної половини 110, отже
        // загальна довжина 220; int потрібен лише малюванню, стан анімації лишається дробовим.
        g.drawLine((int) (cx - dx), (int) (cy - dy), (int) (cx + dx), (int) (cy + dy)); // Обидва кінці обертаються навколо поточної точки (cx,cy).
        g.setColor(new Color(220, 70, 50)); // Точку опори виділяємо червоним.
        // fillOval приймає лівий верхній кут обмежувального прямокутника та його ширину/висоту. Віднімання
        // половини розміру від координати центра потрібне, щоб фігура була центрована на точці, а не починалася в
        // ній.
        g.fillOval((int) cx - 6, cy - 6, 12, 12); // Малюємо коло радіуса 6 навколо точки опори.
        g.drawString("Червона точка рухається по сірому відрізку; синій обертається навколо неї.", 24, 35); // Пояснюємо прийняте трактування руху без технічних деталей.
        // Звільняємо тільки копію контексту, створену через create(). Початковий graphics належить Swing, тому
        // його тут не закриваємо.
        g.dispose(); // Звільняємо створену копію графічного контексту.
    }
}
