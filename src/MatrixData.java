import java.io.IOException; // Стандартний виняток для помилок читання файлу.
import java.nio.charset.StandardCharsets; // UTF-8 робить текстовий формат переносним.
import java.nio.file.Files; // Читаємо вхідний текст із вибраного шляху.
import java.nio.file.Path; // Представляємо ім'я файлу об'єктом Path.
// class описує тип об’єктів; new створює конкретний об’єкт і викликає його конструктор. public робить клас
// доступним ззовні; final у заголовку класу, якщо він є, забороняє створювати підкласи, але сам по собі не робить
// поля незмінними.
public final class MatrixData { // Обчислення відокремлено від Swing для перевірки без графічного екрана.
    // static означає, що метод належить класу: його можна викликати без створення об’єкта. public дозволяє виклик
    // з інших класів, private обмежує використання цим класом; тип перед назвою задає результат, а void означає
    // відсутність значення для повернення.
    public static void checkSize(int n) { // Спільне правило допустимого розміру.
        // throw — аналог raise у Python: негайно припиняємо звичайний хід методу й передаємо об’єкт помилки
        // найближчому відповідному catch. new створює виняток, а текст конструктора пояснює причину користувачу.
        if (n < 1 || n > 15) throw new MatrixSizeException("Розмір n має бути від 1 до 15."); // Демонструємо власний виняток на конкретних даних n=0 або n=16.
    }
    public static int[] compare(double[][] a, double[][] b) { // Алгоритм повторює лабораторну 1, завдання 3.
        // new тип[...] створює масив фіксованої довжини: додати елемент через append, як у Python list, не можна.
        // Числові клітинки без явних значень спочатку дорівнюють 0, boolean — false, а посилання на об’єкти —
        // null. Індекси починаються з 0; вихід за межі спричиняє виняток.
        // .length — незмінне поле масиву, тому пишеться без дужок, аналог len(a). Останній індекс — length - 1. Не
        // плутати: для String потрібен метод length(), а для ArrayList — size().
        int[] result = new int[a.length]; // Один результат для кожного рядка.
        // У for спочатку один раз задається лічильник, перед кожним проходом перевіряється умова, а після проходу
        // виконується i++ або j++. Умова i < n відповідає Python range(n): значення n вже не входить у цикл.
        for (int i = 0; i < a.length; i++) { // Перебираємо рядки квадратних матриць.
            result[i] = 1; // Початкова гіпотеза: всі елементи A строго більші.
            // Для відповіді 1 потрібні правильні порівняння В УСІХ стовпцях. Після першого порушення 0 більше не
            // змінюється на 1, навіть якщо наступна пара підходить; рівність також є порушенням строгого A > B.
            for (int j = 0; j < a.length; j++) if (a[i][j] <= b[i][j]) result[i] = 0; // Рівність також порушує строгу нерівність.
        }
        return result; // Повертаємо вектор нулів та одиниць.
    }
    // throws у заголовку попереджає викликача про перевірюваний виняток: Java вимагає його перехопити або теж
    // оголосити throws. Це не команда кинути помилку — її кидає throw усередині; у Python такої обов’язкової
    // декларації немає.
    public static double[][][] read(Path path) throws IOException { // Формат: n, потім n*n чисел A, потім n*n чисел B.
        // trim() повертає рядок без звичайних крайніх пробілів і символів із кодами до U+0020; оригінальний String
        // не змінюється. Це близько до strip() у Python, але набір прибраних символів не цілком однаковий.
        String text = Files.readString(path, StandardCharsets.UTF_8).trim(); // Помилка відкриття природно породжує IOException.
        if (text.isEmpty()) throw new NumberFormatException("Файл порожній."); // Порожній файл не містить навіть розміру.
        // На відміну від Python str.split, Java String.split приймає регулярний вираз. У рядку Java зворотну риску
        // треба подвоїти: "\\s+" передає шаблону правило «один або більше пробільних символів», а "\\." — буквальну
        // крапку, не будь-який символ.
        String[] parts = text.split("\\s+"); // Рядки та пробіли рівнозначно відділяють числа.
        // Integer.parseInt перетворює текст у примітивний int, подібно до int(text) у Python. Некоректний текст
        // або число за межами -2147483648..2147483647 спричиняє NumberFormatException; тип змінної в Java при
        // цьому залишається фіксованим.
        int n = Integer.parseInt(parts[0]); // Нечисловий розмір породжує NumberFormatException.
        checkSize(n); // Неприпустимий числовий розмір породжує MatrixSizeException.
        // Одне значення займає n, ще n*n — матриця A і стільки ж — B. Точна перевірка кількості до циклів
        // запобігає читанню за межами масиву та ігноруванню зайвих чисел.
        if (parts.length != 1 + 2 * n * n) throw new NumberFormatException("Після n потрібно рівно " + 2 * n * n + " чисел."); // Відхиляємо і недостатні, і зайві дані.
        // double[][] — масив рядків, кожен рядок теж масив; new double[n][n] створює окремий рядок для кожного
        // індексу. a[i][j] означає рядок i, стовпець j. На відміну від Python [[0]*n]*n, тут рядки не посилаються
        // на один спільний список.
        // Три індекси читаються як [номер матриці][рядок][стовпець]: 0 обирає A, 1 — B. Зовнішній масив містить
        // дві незалежні квадратні матриці; це спосіб повернути обидві одним результатом методу.
        double[][][] values = new double[2][n][n]; // Перший індекс обирає матрицю A або B.
        int index = 1; // Перший елемент уже використано для n.
        for (int matrix = 0; matrix < 2; matrix++) { // Послідовно заповнюємо дві матриці.
            for (int i = 0; i < n; i++) { // Перебираємо рядки.
                for (int j = 0; j < n; j++) { // Перебираємо стовпці.
                    // Double.parseDouble перетворює рядок у 64-бітне дробове число double, близький аналог
                    // float(text) у Python. Десятковий роздільник має бути крапкою; replace коми, де він є, робить
                    // введення зручнішим.
                    // Постфіксний index++ спочатку дає старий індекс для читання елемента, а потім збільшує його
                    // на 1. Так послідовно споживаємо числа спочатку A, потім B; parts[0] із розміром уже
                    // пропущено.
                    double value = Double.parseDouble(parts[index++].replace(',', '.')); // Читаємо наступне число й пересуваємо індекс.
                    // Double.isFinite(...) повертає true лише для звичайного скінченного числа; ! заперечує
                    // результат. double може містити NaN («не число») і ±Infinity, тому успішний parseDouble ще не
                    // гарантує придатність числа для формули. У Python аналог — math.isfinite(x); ця перевірка не
                    // перевіряє точність округлення.
                    if (!Double.isFinite(value)) throw new NumberFormatException("NaN та Infinity заборонені."); // Забороняємо спеціальні значення double.
                    values[matrix][i][j] = value; // Записуємо число в потрібну клітинку.
                }
            }
        }
        return values; // Повертаємо пару повністю перевірених матриць.
    }
}
